/**
 * Bundled wallet skill for dsh-web3.
 *
 * DSH 0.2+ merges skills from providers registered on `ctx.skills`
 * (`@deepseek-ai/dsh-skill`). The plugin registers a bundled provider for
 * `skills/dsh-web3-wallet/SKILL.md`, so the skill appears in every session's
 * catalog while the plugin is loaded and disappears with it — nothing is
 * written to the user's skill folder.
 *
 * Earlier releases mirrored the file into `$DSH_HOME/skills`. A user-folder
 * skill outranks a bundled one, so a stale mirror would shadow the current
 * skill: copies whose content matches a version we shipped (or that carry
 * the managed marker) are removed; anything else is a user edit and is kept.
 *
 * Hosts without a skill registry still get the marked mirror as a fallback.
 *
 * @module dsh-web3/skills
 */

import { createHash } from 'node:crypto';
import { mkdir, readFile, rm, rmdir, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Context, Logger } from '@deepseek-ai/cordis';

/** Skill name (kebab-case), matching the bundle directory name. */
export const SKILL_NAME = 'dsh-web3-wallet';

/** Provider name in the `ctx.skills` registry. */
export const SKILL_PROVIDER = 'dsh-web3';

/** Same rank DSH uses for packaged skills (`BUNDLED_SKILL_RANK`): user and project skills still override. */
const BUNDLED_RANK = 600;

/** First line of every fallback mirror we write, so later versions can recognize and remove it. */
export const MANAGED_MARKER = '<!-- dsh-web3: managed copy, regenerated by the plugin; edits are overwritten -->';

/** sha256 of every SKILL.md previously mirrored into the user skill folder (0.3.x – 0.7.0-dev). */
const LEGACY_MIRROR_SHA256 = new Set([
  '5f91d123233752e152455111a76c1acfd2753e854ff13e170f41ce3229654053',
  '149353459c2fd119c989c1361d9afecc5290ccaf4cbaa707b8e078132324094f',
  '47b7514578bcfdf9324face42e95267843083229370aab9ea0456f2b608505cd',
]);

/** Resolve the DSH user skill root, matching dsh-home-paths. */
export function dshUserSkillsRoot(): string {
  const dshHome = process.env.DSH_HOME ?? join(homedir(), '.dsh');
  return join(dshHome, 'skills');
}

/** Absolute path of the bundled SKILL.md inside this package. */
export function bundledSkillPath(): string {
  const selfDir = dirname(fileURLToPath(import.meta.url)); // <pkg>/lib
  return join(selfDir, '..', 'skills', SKILL_NAME, 'SKILL.md');
}

/** Target path under the DSH user skill root. */
export function userSkillPath(root = dshUserSkillsRoot()): string {
  return join(root, SKILL_NAME, 'SKILL.md');
}

/** Parsed SKILL.md: routing metadata from the frontmatter plus the instruction body. */
export interface ParsedSkill {
  name: string;
  description: string;
  whenToUse?: string;
  body: string;
}

/** Read the single-line `key: value` fields our frontmatter uses (no YAML dependency). */
export function parseSkillFile(text: string): ParsedSkill {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(text);
  if (match === null) throw new Error('SKILL.md has no frontmatter');
  const fields: Record<string, string> = {};
  for (const line of (match[1] ?? '').split(/\r?\n/)) {
    const field = /^([A-Za-z][\w-]*):\s*(.*)$/.exec(line);
    if (field === null) continue;
    const value = (field[2] ?? '').trim().replace(/^(['"])(.*)\1$/, '$2');
    if (value !== '') fields[field[1] ?? ''] = value;
  }
  const name = fields.name;
  const description = fields.description;
  if (name === undefined || description === undefined) throw new Error('SKILL.md frontmatter needs name and description');
  return {
    name,
    description,
    ...(fields.whenToUse !== undefined ? { whenToUse: fields.whenToUse } : {}),
    body: text.slice(match[0].length).replace(/^\s+/, ''),
  };
}

/** Structural subset of `@deepseek-ai/dsh-skill`'s provider contract this plugin implements. */
interface BundledSkillProvider {
  readonly name: string;
  list(): Promise<readonly Record<string, unknown>[]>;
  get(candidate: unknown): Promise<Record<string, unknown> | undefined>;
}

/** Minimal `ctx.skills` surface (DSH `SkillRegistry`). */
interface SkillRegistryLike {
  registerProvider(create: (control: { signal: AbortSignal; invalidate: () => void }) => BundledSkillProvider): () => void;
}

/**
 * The bundled provider. The file is re-read on every load, so a plugin
 * upgrade (or a local edit while developing) is picked up without restart.
 */
export function createSkillProvider(path = bundledSkillPath()): BundledSkillProvider {
  const resourceBase = { kind: 'directory' as const, path: dirname(path) };
  const invocation = { modelInvocable: true, userInvocable: true };
  const summary = (parsed: ParsedSkill) => ({
    path,
    name: parsed.name,
    description: parsed.description,
    ...(parsed.whenToUse !== undefined ? { whenToUse: parsed.whenToUse } : {}),
    invocation,
    source: 'bundled',
    provider: SKILL_PROVIDER,
    resourceBase,
  });
  return {
    name: SKILL_PROVIDER,
    async list() {
      const parsed = parseSkillFile(await readFile(path, 'utf8'));
      return [{ ...summary(parsed), rank: BUNDLED_RANK, locator: path }];
    },
    async get() {
      const parsed = parseSkillFile(await readFile(path, 'utf8'));
      return { ...summary(parsed), content: parsed.body };
    },
  };
}

function sha256(text: string): string {
  return createHash('sha256').update(text).digest('hex');
}

/**
 * Remove a mirror an earlier release (or the fallback) wrote into the user
 * skill folder; a user-edited copy is left alone with a warning. Never throws.
 */
export async function removeLegacySkillMirror(logger: Pick<Logger, 'info' | 'warn'>, root = dshUserSkillsRoot()): Promise<'removed' | 'kept' | 'absent'> {
  const target = userSkillPath(root);
  let existing: string;
  try {
    existing = await readFile(target, 'utf8');
  } catch {
    return 'absent';
  }
  if (!existing.startsWith(MANAGED_MARKER) && !LEGACY_MIRROR_SHA256.has(sha256(existing))) {
    logger.warn(`${target} is a user-edited copy of ${SKILL_NAME}; it overrides the bundled skill. Delete it to use the version shipped with the plugin.`);
    return 'kept';
  }
  try {
    await rm(target, { force: true });
    await rmdir(dirname(target)).catch(() => undefined); // only when empty
    logger.info(`removed stale ${SKILL_NAME} mirror at ${target}; the bundled skill is served through ctx.skills`);
    return 'removed';
  } catch (error) {
    logger.warn(`could not remove stale skill mirror ${target}: ${error instanceof Error ? error.message : String(error)}`);
    return 'kept';
  }
}

/**
 * Fallback for hosts without `ctx.skills`: mirror the bundled skill into the
 * user skill folder (marked, so it is replaced or removed later). A copy the
 * user edited is never overwritten. Never throws.
 */
export async function syncBundledSkill(logger: Pick<Logger, 'info' | 'warn' | 'debug'>, root = dshUserSkillsRoot()): Promise<void> {
  try {
    const sourceText = `${MANAGED_MARKER}\n${await readFile(bundledSkillPath(), 'utf8')}`;
    const target = userSkillPath(root);
    try {
      const existing = await readFile(target, 'utf8');
      if (existing === sourceText) {
        logger.debug(`skill ${SKILL_NAME} already up to date at ${target}`);
        return;
      }
      if (!existing.startsWith(MANAGED_MARKER) && !LEGACY_MIRROR_SHA256.has(sha256(existing))) {
        logger.warn(`${target} was edited by the user; leaving it in place`);
        return;
      }
    } catch {
      // Target missing — write it.
    }
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, sourceText, 'utf8');
    logger.info(`synced bundled skill ${SKILL_NAME} to ${target} (host has no skill registry)`);
  } catch (error) {
    logger.warn(`skill sync failed: ${error instanceof Error ? error.message : String(error)}`);
  }
}

/**
 * Serve the wallet skill for the lifetime of the plugin: through
 * `ctx.skills` whenever the registry is (or becomes) available, otherwise
 * through the marked mirror.
 */
export function provideBundledSkill(ctx: Context, logger: Logger): void {
  const register = (scoped: Context) => {
    const registry = (scoped as unknown as { skills?: SkillRegistryLike }).skills;
    if (registry === undefined) return;
    registry.registerProvider(() => createSkillProvider());
    logger.info(`bundled skill ${SKILL_NAME} registered on ctx.skills`);
    void removeLegacySkillMirror(logger);
  };
  const inject = (ctx as unknown as { inject?: (deps: string[], callback: (scoped: Context) => void) => unknown }).inject;
  if (typeof inject === 'function') inject.call(ctx, ['skills'], register);
  if (ctx.get('skills') === undefined) void syncBundledSkill(logger);
}
